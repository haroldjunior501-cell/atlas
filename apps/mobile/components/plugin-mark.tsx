export function PluginMark({ provider, label, size = 44 }: { provider: string; label: string; size?: number }) {
  const mark = MARKS[provider]
  const radius = Math.round(size * 0.26)
  if (!mark) {
    return (
      <View style={[styles.wrap, { width: size, height: size, borderRadius: radius, backgroundColor: '#2563eb' }]}>
        <Text style={[styles.letter, { fontSize: size * 0.4 }]}>{(label || provider).slice(0, 1).toUpperCase()}</Text>
      </View>
    )
  }
  const glyph = Math.round(size * (mark.scale ?? 0.55))
  return (
    <View style={[styles.wrap, { width: size, height: size, borderRadius: radius, backgroundColor: mark.bg }]}>
      <Svg width={glyph} height={glyph} viewBox={mark.viewBox} preserveAspectRatio="xMidYMid meet">
        {mark.rects?.map((rect, i) => (
          <Rect key={`r${i}`} x={rect.x} y={rect.y} width={rect.width} height={rect.height} rx={rect.rx} fill={rect.fill} />
        ))}
        {mark.circles?.map((circle, i) => (
          <Circle key={`c${i}`} cx={circle.cx} cy={circle.cy} r={circle.r} fill={circle.fill} />
        ))}
        {(mark.paths || []).map((path, i) => (
          <Path key={`p${i}`} d={path.d} fill={path.fill} />
        ))}
      </Svg>
    </View>
  )
}

const styles = StyleSheet.create({
  wrap: {
    alignItems: 'center',
    justifyContent: 'center',
    overflow: 'hidden',
    borderWidth: StyleSheet.hairlineWidth,
    borderColor: 'rgba(255,255,255,0.14)',
  },
  letter: { color: '#fff', fontWeight: '800' },
})
